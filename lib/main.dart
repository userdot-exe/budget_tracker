import 'screens/analytics_screen.dart';
import 'screens/budget_screen.dart';
import 'screens/dashboard_screen.dart';
import 'screens/expense_screen.dart';
import 'screens/income_screen.dart';
import 'screens/settings_screen.dart';
import 'services/database_service.dart';
import 'utils/app_theme.dart';
import 'widgets/expense_form.dart';
import 'widgets/income_form.dart';
import 'widgets/month_selector.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // firebase_options.dart is generated by `flutterfire configure`.
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // Turns on offline storage, uploads sample data on first launch,
  // and loads everything before the first screen shows.
  await db.init();

  runApp(const BudgetTrackerApp());
}

class BudgetTrackerApp extends StatelessWidget {
  const BudgetTrackerApp({super.key});

  @override
  Widget build(BuildContext context) {
    return ListenableBuilder(
      listenable: db,
      builder: (context, _) => MaterialApp(
        title: 'Personal Budget Tracker',
        debugShowCheckedModeBanner: false,
        themeMode: db.themeMode,
        theme: buildAppTheme(Brightness.light),
        darkTheme: buildAppTheme(Brightness.dark),
        home: const HomeShell(),
      ),
    );
  }
}

/// Bottom navigation: Dashboard, Income, Expenses, Budget, Analytics.
/// Settings opens from the gear icon (Section 16).
class HomeShell extends StatefulWidget {
  const HomeShell({super.key});

  @override
  State<HomeShell> createState() => _HomeShellState();
}

class _HomeShellState extends State<HomeShell> {
  int _index = 0;

  static const _titles = ['Dashboard', 'Income', 'Expenses', 'Budget', 'Analytics'];

  void _goTo(int index) => setState(() => _index = index);

  Widget? _fab() {
    if (_index == 1) {
      return FloatingActionButton.extended(
        onPressed: () => showIncomeForm(context),
        icon: const Icon(Icons.add),
        label: const Text('Add income'),
      );
    }
    if (_index == 2) {
      return FloatingActionButton.extended(
        onPressed: () => showExpenseForm(context),
        icon: const Icon(Icons.add),
        label: const Text('Add expense'),
      );
    }
    return null;
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        toolbarHeight: 64,
        title: Text(_titles[_index]),
        actions: [
          const Center(child: MonthSelector()),
          IconButton(
            tooltip: 'Settings',
            icon: const Icon(Icons.settings_outlined),
            onPressed: () => Navigator.push(
              context,
              MaterialPageRoute(builder: (_) => const SettingsScreen()),
            ),
          ),
          const SizedBox(width: 8),
        ],
      ),
      body: Column(
        children: [
          // Only shows when Firebase refuses a save, e.g. expired test-mode rules.
          ListenableBuilder(
            listenable: db,
            builder: (context, _) {
              final message = db.syncError;
              if (message == null) return const SizedBox.shrink();
              final c = context.colors;
              return Container(
                width: double.infinity,
                margin: const EdgeInsets.fromLTRB(20, 0, 20, 8),
                padding: const EdgeInsets.fromLTRB(14, 6, 4, 6),
                decoration: BoxDecoration(
                  color: c.danger.withValues(alpha: 0.1),
                  borderRadius: BorderRadius.circular(12),
                ),
                child: Row(
                  children: [
                    Expanded(
                      child: Text(message,
                          style: TextStyle(color: c.danger, fontSize: 13, fontWeight: FontWeight.w500)),
                    ),
                    IconButton(
                      tooltip: 'Dismiss',
                      icon: Icon(Icons.close, size: 18, color: c.danger),
                      onPressed: db.dismissSyncError,
                    ),
                  ],
                ),
              );
            },
          ),
          Expanded(
            child: IndexedStack(
              index: _index,
              children: [
                DashboardScreen(onNavigate: _goTo),
                const IncomeScreen(),
                const ExpenseScreen(),
                const BudgetScreen(),
                const AnalyticsScreen(),
              ],
            ),
          ),
        ],
      ),
      floatingActionButton: _fab(),
      bottomNavigationBar: DecoratedBox(
        decoration: BoxDecoration(border: Border(top: BorderSide(color: context.colors.line))),
        child: NavigationBar(
          selectedIndex: _index,
          onDestinationSelected: _goTo,
          destinations: const [
            NavigationDestination(
              icon: Icon(Icons.space_dashboard_outlined),
              selectedIcon: Icon(Icons.space_dashboard),
              label: 'Dashboard',
            ),
            NavigationDestination(
              icon: Icon(Icons.south_west_rounded),
              label: 'Income',
            ),
            NavigationDestination(
              icon: Icon(Icons.receipt_long_outlined),
              selectedIcon: Icon(Icons.receipt_long),
              label: 'Expenses',
            ),
            NavigationDestination(
              icon: Icon(Icons.account_balance_wallet_outlined),
              selectedIcon: Icon(Icons.account_balance_wallet),
              label: 'Budget',
            ),
            NavigationDestination(
              icon: Icon(Icons.insights_outlined),
              selectedIcon: Icon(Icons.insights),
              label: 'Analytics',
            ),
          ],
        ),
      ),
    );
  }
}
